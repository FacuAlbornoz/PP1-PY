from fastapi import FastAPI

app = FastAPI()

app.title = "Mi primera API"  # Así cambia el nombre en /docs

# METODOS: GET POST PUT DELETE


@app.get("/saludo")  # "/Saludo" es el endpoint de la url
async def saludo():
    return {"hola": "mundo"}


@app.put("/saludo/put")
async def put():
    return {"hola": "put"}


@app.post("/saludo/post")
async def post():
    return {"hola": "post"}


@app.delete("/saludo/delete")
async def delete():
    return {"hola": "delete"}
